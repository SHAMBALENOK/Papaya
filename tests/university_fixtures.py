"""Синтетические приказы вузов для тестов разбора.

Реальный вузовский документ один — приказ ИТМО (``app/tables/rsosh_bvi/
rsosh_bvi.pdf``), и на нём нельзя проверить все раскладки: перенос шапки на
вторую страницу, объединённая колонка направления, зеркальная шапка, строки
без олимпиады. Поэтому основная проверка идёт на коротких таблицах, повторяющих
настоящую раскладку приказа.

Колонки приказа ИТМО: ``Направление подготовки`` (объединена по вертикали),
``Наименование олимпиады``, ``Профиль олимпиады``, ``Предмет (подтверждающий)``,
``Уровень олимпиады``, ``Диплом``. Шапка письма (министерство + вуз) печатается
над таблицей приказа отдельной короткой таблицей.
"""

from app.rsosh.extraction import PageTables

#: Шапка письма: министерство и полное наименование вуза с кратким в скобках.
LETTERHEAD = [
    ['Министерство науки и высшего образования Российской Федерации'],
    [
        'федеральное государственное автономное образовательное учреждение '
        'высшего образования «Национальный исследовательский университет '
        'ИТМО» (Университет ИТМО)'
    ],
]

#: Шапка таблицы приказа (прямая, не зеркальная).
ORDER_HEADER = [
    'Направление подготовки',
    'Наименование олимпиады',
    'Профиль олимпиады',
    'Предмет (подтверждающий)',
    'Уровень олимпиады',
    'Диплом',
]


def order_row(
    direction: str = '',
    name: str = '',
    profile: str = 'Информатика',
    subject: str = 'Информатика',
    level: str = '1',
    diploma: str = 'Победитель или призер',
) -> list[str]:
    """Одна строка таблицы приказа в порядке колонок ИТМО."""
    return [direction, name, profile, subject, level, diploma]


def page(page_number: int, tables, *, method: str = 'text') -> PageTables:
    """Страница документа с набором таблиц."""
    return PageTables(page=page_number, method=method, tables=tables)


def letterhead_page(page_number: int, order_tables, *, method: str = 'text'):
    """Страница: шапка письма отдельной таблицей + таблица(ы) приказа."""
    return page(
        page_number,
        [list(LETTERHEAD), *order_tables],
        method=method,
    )


def reverse(text: str) -> str:
    """Зеркальная строка — как печатает шапку часть приказов."""
    return text[::-1]
